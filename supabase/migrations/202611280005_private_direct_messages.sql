-- Bading Tambayan: private one-to-one direct messages for website-wide chat heads.
-- Only the two participants can read a conversation or its messages.

create table if not exists public.dm_conversations (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.dm_participants (
  conversation_id uuid not null references public.dm_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_read_at timestamptz,
  primary key (conversation_id, user_id)
);

create index if not exists dm_participants_user_id_idx
  on public.dm_participants(user_id, conversation_id);

create table if not exists public.dm_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.dm_conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists dm_messages_conversation_created_idx
  on public.dm_messages(conversation_id, created_at desc, id desc);

alter table public.dm_conversations enable row level security;
alter table public.dm_participants enable row level security;
alter table public.dm_messages enable row level security;

-- SECURITY DEFINER helper avoids recursive RLS when participant policies
-- need to check membership in the same table.
create or replace function public.is_dm_participant(p_conversation_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $
  select exists (
    select 1 from public.dm_participants p
    where p.conversation_id = p_conversation_id
      and p.user_id = auth.uid()
  );
$;

revoke all on function public.is_dm_participant(uuid) from public;
grant execute on function public.is_dm_participant(uuid) to authenticated;

drop policy if exists "DM participants can read their conversations" on public.dm_conversations;
create policy "DM participants can read their conversations"
  on public.dm_conversations for select to authenticated
  using (public.is_dm_participant(id));

drop policy if exists "DM participants can read participant lists" on public.dm_participants;
create policy "DM participants can read participant lists"
  on public.dm_participants for select to authenticated
  using (public.is_dm_participant(conversation_id));

drop policy if exists "DM participants can read messages" on public.dm_messages;
create policy "DM participants can read messages"
  on public.dm_messages for select to authenticated
  using (public.is_dm_participant(conversation_id));

drop policy if exists "DM participants can send as themselves" on public.dm_messages;
create policy "DM participants can send as themselves"
  on public.dm_messages for insert to authenticated
  with check (
    sender_id = auth.uid()
    and public.is_dm_participant(conversation_id)
  );

grant select on public.dm_conversations to authenticated;
grant select on public.dm_participants to authenticated;
grant select, insert on public.dm_messages to authenticated;

-- Create or retrieve the existing one-to-one conversation for this pair.
-- Membership rows cannot be created directly by clients.
create or replace function public.open_direct_conversation(target_user_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  me uuid := auth.uid();
  found_id uuid;
  new_id uuid;
begin
  if me is null then
    raise exception 'You must be signed in to start a private chat.';
  end if;
  if target_user_id is null or target_user_id = me then
    raise exception 'Choose another member to start a private chat.';
  end if;
  if not exists (
    select 1 from public.chat_profiles cp where cp.user_id = target_user_id
  ) then
    raise exception 'That member could not be found.';
  end if;

  -- Serialize creation for this pair to avoid duplicate conversations.
  perform pg_advisory_xact_lock(hashtextextended(
    least(me::text, target_user_id::text) || ':' ||
    greatest(me::text, target_user_id::text), 0
  ));

  select c.id into found_id
  from public.dm_conversations c
  where exists (
    select 1 from public.dm_participants a
    where a.conversation_id = c.id and a.user_id = me
  )
  and exists (
    select 1 from public.dm_participants b
    where b.conversation_id = c.id and b.user_id = target_user_id
  )
  and (
    select count(*) from public.dm_participants x
    where x.conversation_id = c.id
  ) = 2
  limit 1;

  if found_id is not null then
    return found_id;
  end if;

  insert into public.dm_conversations default values returning id into new_id;
  insert into public.dm_participants (conversation_id, user_id)
  values (new_id, me), (new_id, target_user_id);
  return new_id;
end;
$$;

revoke all on function public.open_direct_conversation(uuid) from public;
grant execute on function public.open_direct_conversation(uuid) to authenticated;

-- Enable realtime delivery for newly inserted private messages.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'dm_messages'
  ) then
    alter publication supabase_realtime add table public.dm_messages;
  end if;
end;
$$;
