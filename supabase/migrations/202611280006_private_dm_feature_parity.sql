-- Private DM feature parity: replies, reactions, private media, and server-side read state.
-- Existing dm_messages rows and the working push-notification flow are preserved.

alter table public.dm_messages
  add column if not exists reply_to bigint
  references public.dm_messages(id) on delete set null;

create index if not exists dm_messages_reply_to_idx
  on public.dm_messages(reply_to);

create table if not exists public.dm_message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.dm_messages(id) on delete cascade,
  conversation_id uuid not null references public.dm_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  emoji text not null check (char_length(emoji) between 1 and 16),
  created_at timestamptz not null default now(),
  unique (message_id, user_id, emoji)
);

create index if not exists dm_message_reactions_message_idx
  on public.dm_message_reactions(message_id);

alter table public.dm_message_reactions enable row level security;

drop policy if exists "DM participants can read reactions" on public.dm_message_reactions;
create policy "DM participants can read reactions"
  on public.dm_message_reactions for select to authenticated
  using (public.is_dm_participant(conversation_id));

drop policy if exists "DM participants can add their own reactions" on public.dm_message_reactions;
create policy "DM participants can add their own reactions"
  on public.dm_message_reactions for insert to authenticated
  with check (
    user_id = auth.uid()
    and public.is_dm_participant(conversation_id)
    and exists (
      select 1 from public.dm_messages m
      where m.id = message_id and m.conversation_id = conversation_id
    )
  );

drop policy if exists "Users can remove their own DM reactions" on public.dm_message_reactions;
create policy "Users can remove their own DM reactions"
  on public.dm_message_reactions for delete to authenticated
  using (user_id = auth.uid() and public.is_dm_participant(conversation_id));

grant select, insert, delete on public.dm_message_reactions to authenticated;

-- Read state is stored per participant in the database, so inbox badges stay in sync
-- across the website and the Android companion app.
create or replace function public.mark_dm_read(p_conversation_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null or not public.is_dm_participant(p_conversation_id) then
    raise exception 'You are not a participant in this conversation.';
  end if;

  update public.dm_participants
  set last_read_at = now()
  where conversation_id = p_conversation_id
    and user_id = auth.uid();
end;
$$;

revoke all on function public.mark_dm_read(uuid) from public;
grant execute on function public.mark_dm_read(uuid) to authenticated;

create or replace function public.get_my_dm_unread_counts()
returns table (conversation_id uuid, unread_count bigint, last_read_at timestamptz)
language sql
stable
security invoker
set search_path = public, auth
as $$
  select p.conversation_id,
         count(m.id) filter (
           where m.sender_id <> auth.uid()
             and (p.last_read_at is null or m.created_at > p.last_read_at)
         ) as unread_count,
         p.last_read_at
  from public.dm_participants p
  left join public.dm_messages m on m.conversation_id = p.conversation_id
  where p.user_id = auth.uid()
  group by p.conversation_id, p.last_read_at;
$$;

revoke all on function public.get_my_dm_unread_counts() from public;
grant execute on function public.get_my_dm_unread_counts() to authenticated;

-- Dedicated private media bucket. Paths: conversation_id/user_id/filename.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'dm-media',
  'dm-media',
  false,
  10485760,
  array['image/jpeg','image/png','image/webp','image/gif','audio/webm','audio/mp4','audio/ogg','audio/mpeg','audio/wav']
)
on conflict (id) do update
set public = false,
    file_size_limit = 10485760,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "DM participants can upload their own media" on storage.objects;
create policy "DM participants can upload their own media"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'dm-media'
    and split_part(name, '/', 2) = auth.uid()::text
    and public.is_dm_participant((split_part(name, '/', 1))::uuid)
  );

drop policy if exists "DM participants can read conversation media" on storage.objects;
create policy "DM participants can read conversation media"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'dm-media'
    and public.is_dm_participant((split_part(name, '/', 1))::uuid)
  );

drop policy if exists "Users can delete their own DM media" on storage.objects;
create policy "Users can delete their own DM media"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'dm-media'
    and split_part(name, '/', 2) = auth.uid()::text
    and public.is_dm_participant((split_part(name, '/', 1))::uuid)
  );

-- Realtime reaction updates are used by open private conversations.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'dm_message_reactions'
  ) then
    alter publication supabase_realtime add table public.dm_message_reactions;
  end if;
end;
$$;
